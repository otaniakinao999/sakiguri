/**
 * 口座の欄のラベル（FR-52・AC-58e）
 *
 * | 収支 | ラベル |
 * |---|---|
 * | 支出 | 支払元 |
 * | 収入 | 入金先 |
 * | 振替 | 振替元 |
 *
 * **「支払方法」では収入で意味が通らない。** ファクタリングの入金に
 * 「支払方法」と出ていた。振替のときは「振替先」と対になるよう
 * 「振替元」にする ―― 「支払方法」と「振替先」は対になっていなかった。
 *
 * **`Record` で持つ。** 収支が増えたときに、ここの漏れが型で落ちる
 * （CLAUDE.md §2.8 の「列挙は集合と突き合わせる」）。
 *
 * **カードは支出のときだけ候補に出る**ので、支出のラベルは「支払元」で
 * 足りる。
 *
 * ## 置き場所（2026-11-15）
 *
 * **実績編集（`ActualForm`）と予定の設定（`EntryFields`）が同じ対応を
 * 使う**（AC-58e を v1.54 で予定の設定にも広げた）。**同じ表を2箇所に
 * 書くと、収支が増えたときに片方だけ古くなる**ので、ここ1つに置いて
 * 両方から引く（§2.8）。
 *
 * **対象は「行が収支を持つ欄」に限る。** 仕分けルールの「口座」
 * （`RulesTable`。「すべての口座」を含む絞り込み）と、カードの
 * 「引落口座」（`AccountsTable`）は対象外である ―― どちらも行の収支で
 * 決まる欄ではない。
 *
 * ## 表の中では、見える語は列見出しのままである
 *
 * 予定の設定は表で、**列見出しは全行で1つ**（並べ替えのキーでもある）。
 * 行ごとに違う語を見出しに出すことはできないので、**見出しは「口座」の
 * まま**で、行ごとに変わるのは**欄の読み上げ名**（`aria-label`）である。
 * 実績編集はフォームなので、そちらは見える語が変わる。
 */

