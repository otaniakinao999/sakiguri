/* ========================= CL-8 借入返済（v2.0） ========================= */

describe("AC-11（v2.0）借入返済スケジュールの生成", () => {
  /*
   * 基準：元本500万円・年利2.0%・期間60ヶ月・据置6ヶ月・元利均等の借入について、
   *       据置期間中の支払額が利息のみとなり、7回目から元利均等額に切り替わること。
   *       返済表の元金合計が500万円と一致すること。
   *
   * 素材：{ principal: 5_000_000, annualRate: 2.0, termMonths: 60,
   *         graceMonths: 6, method: 'equalTotal', payDay: 27 }
   *
   * 期待：
   *   月利 r = 2.0 ÷ 12 ÷ 100 = 0.0016666...
   *   1〜6回目（据置中）は利息のみ。5,000,000 × r = 8,333.33... → 8,333円
   *     （CL-8 は円未満を**切り捨て**る。CL-4 の Math.round とは規則が違う）
   *   1〜6回目の元金充当は 0
   *   7回目から元利均等額に切り替わる。n = 60 − 6 = 54
   *     毎回返済額 = 5,000,000 × r ÷ (1 − (1 + r)^(−54))
   *   元金充当の合計 = 5,000,000 ちょうど（最終回で残額を調整する）
   *
   * 注意：CLAUDE.md §2.1 が名指ししている箇所。60回の積み上げで1円の誤差が
   *       60円になるため、合計一致はテストで保証すること。
   */
  it.todo("据置期間中の支払額が利息のみになる");
  it.todo("7回目から元利均等額に切り替わる");
  it.todo("返済表の元金合計が元本と一致する（元利均等）");
  it.todo("返済表の元金合計が元本と一致する（元金均等）");
  it.todo("返済表の元金合計が元本と一致する（期日一括）");
  it.todo("返済日は min(payDay, その月の末日) に丸める");
});

